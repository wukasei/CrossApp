    public static IReadOnlyList<BookCopy> Generate(int count)
    {
        var list = new List<BookCopy>(count);
        for (int i = 0; i < count; i++)
        {
            var copy = BookCopy.Create($"G-{i:D6}", $"978-000-{i % 500:D3}", $"Книга {i % 500}", 1950 + i % 75, null);
            if (i % 4 == 0)
                copy.Issue();
            list.Add(copy);
        }
        return list;
    }

    // Create завжди створює примірник «на полиці», тому видані/списані
